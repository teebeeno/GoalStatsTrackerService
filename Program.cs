#region Import Endpoints
app.MapPost("/import", async (AppDbContext db, ImportDto data) =>
{
    Console.WriteLine($"Importing {data.Teams.Count} teams and {data.Matches.Count} matches...");
    var teamIds = data.Teams.Select(t => t.Id).ToHashSet();
    var orphan = data.Matches.FirstOrDefault(m => !teamIds.Contains(m.TeamId));
    if (orphan != null)
    {
        return Results.BadRequest($"Match {orphan.Id} belongs to unknown team {orphan.TeamId}.");
    }

    await using var transaction = await db.Database.BeginTransactionAsync();
    // Deleting the teams cascades to players, matches and goals
    await db.Teams.ExecuteDeleteAsync();
    db.Teams.AddRange(data.Teams.Select(t => t.ToModel(t.Id)));
    db.Matches.AddRange(data.Matches.Select(m => m.ToModel(m.Id)));
    await db.SaveChangesAsync();
    await transaction.CommitAsync();
    return Results.NoContent();
});
#endregion


